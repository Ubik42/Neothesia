import type { LoadedSong } from "./api";
import type { ScoreMapping } from "./ScoreNoteEditor";
import type { PaperRegion } from "./PaperAnnotations";

export interface LocatedPaperNote {
  track: number;
  index: number;
  pitch: number;
  measure: number;
  page: number;
  rendererId: string;
  region: PaperRegion;
}

export interface LocatedPaperPlan {
  notes: LocatedPaperNote[];
  skipped: number;
  reasons: string[];
}

function regionFor(svg: SVGSVGElement, element: SVGGraphicsElement): PaperRegion | null {
  const matrix = svg.getScreenCTM();
  const box = svg.viewBox.baseVal;
  if (!matrix || box.width <= 0 || box.height <= 0) return null;
  const rect = (element.querySelector(".notehead") as SVGGraphicsElement | null ?? element).getBoundingClientRect();
  if (rect.width <= 0 || rect.height <= 0) return null;
  const inverse = matrix.inverse();
  const first = new DOMPoint(rect.left, rect.top).matrixTransform(inverse);
  const last = new DOMPoint(rect.right, rect.bottom).matrixTransform(inverse);
  const left = Math.min(first.x, last.x), right = Math.max(first.x, last.x);
  const top = Math.min(first.y, last.y), bottom = Math.max(first.y, last.y);
  const x = Math.max(0, (left - box.x) / box.width - 0.004);
  const y = Math.max(0, (top - box.y) / box.height - 0.003);
  const endX = Math.min(1, (right - box.x) / box.width + 0.004);
  const endY = Math.min(1, (bottom - box.y) / box.height + 0.003);
  if (![x, y, endX, endY].every(Number.isFinite) || endX - x < 0.002 || endY - y < 0.002)
    return null;
  return { x, y, width: endX - x, height: endY - y };
}

export function locatedPaperMeasureAt(song: Pick<LoadedSong, "measures">, seconds: number): number | null {
  const position = song.measures.findIndex((item, i) =>
    seconds >= item.start - 0.001 &&
    (seconds < item.end - 0.001 || i === song.measures.length - 1 && seconds <= item.end + 0.001),
  );
  return position < 0 ? null : position + 1;
}

/** Measure only the SVG generated by the current, correlated MusicXML source. */
export function buildLocatedPaperPlan(
  pages: string[], mapping: ScoreMapping[], song: LoadedSong,
): LocatedPaperPlan {
  const noteByIdentity = new Map(song.notes.map((note) => [`${note.track}:${note.index}`, note]));
  const mapped = new Map<string, ScoreMapping[]>();
  for (const item of mapping) {
    const key = `${item.track}:${item.index}`;
    const old = mapped.get(key) ?? [];
    old.push(item);
    mapped.set(key, old);
  }
  const regions = new Map<string, PaperRegion>();
  const host = document.createElement("div");
  host.style.cssText = "position:fixed;left:-10000px;top:0;width:1050px;visibility:hidden;pointer-events:none;";
  document.body.append(host);
  try {
    for (let index = 0; index < pages.length; index++) {
      host.innerHTML = pages[index];
      const svg = host.querySelector("svg") as SVGSVGElement | null;
      if (!svg) continue;
      svg.style.width = "1050px";
      svg.style.height = "auto";
      svg.querySelectorAll<SVGGraphicsElement>("g.note[id]").forEach((element) => {
        const region = regionFor(svg, element);
        if (region) regions.set(`${index}:${element.id}`, region);
      });
    }
  } finally {
    host.remove();
  }
  const notes: LocatedPaperNote[] = [];
  const issues = new Map<string, number>();
  for (const [key, note] of noteByIdentity) {
    const candidates = mapped.get(key) ?? [];
    const unique = new Map(candidates.map((item) => [`${item.page}:${item.id}`, item]));
    if (unique.size !== 1) {
      issues.set("谱音对应不唯一或未配对", (issues.get("谱音对应不唯一或未配对") ?? 0) + 1);
      continue;
    }
    const item = [...unique.values()][0];
    const region = regions.get(`${item.page}:${item.id}`);
    const measure = locatedPaperMeasureAt(song, note.start);
    if (!region || item.pitch !== note.pitch || measure === null) {
      issues.set("谱音位置或小节无法核对", (issues.get("谱音位置或小节无法核对") ?? 0) + 1);
      continue;
    }
    notes.push({ track: note.track, index: note.index, pitch: note.pitch, measure, page: item.page + 1, rendererId: item.id, region });
  }
  return {
    notes,
    skipped: noteByIdentity.size - notes.length,
    reasons: [...issues].map(([name, count]) => `${name} ${count} 处`),
  };
}

export async function svgPagePng(source: string): Promise<number[]> {
  const svg = new DOMParser().parseFromString(source, "image/svg+xml").documentElement as unknown as SVGSVGElement;
  const box = svg.viewBox.baseVal;
  if (box.width <= 0 || box.height <= 0) throw new Error("谱页尺寸无效");
  const width = 1100, height = Math.ceil(width * box.height / box.width);
  if (height > 4200) throw new Error("谱页高度超出可生成范围");
  svg.setAttribute("width", String(width));
  svg.setAttribute("height", String(height));
  const url = URL.createObjectURL(new Blob([new XMLSerializer().serializeToString(svg)], { type: "image/svg+xml" }));
  try {
    const image = new Image();
    image.src = url;
    await image.decode();
    const canvas = document.createElement("canvas");
    canvas.width = width;
    canvas.height = height;
    const context = canvas.getContext("2d");
    if (!context) throw new Error("无法创建谱页画布");
    context.fillStyle = "#ffffff";
    context.fillRect(0, 0, width, height);
    context.drawImage(image, 0, 0, width, height);
    const blob = await new Promise<Blob | null>((resolve) => canvas.toBlob(resolve, "image/png"));
    if (!blob) throw new Error("谱页图片生成失败");
    return Array.from(new Uint8Array(await blob.arrayBuffer()));
  } finally {
    URL.revokeObjectURL(url);
  }
}
